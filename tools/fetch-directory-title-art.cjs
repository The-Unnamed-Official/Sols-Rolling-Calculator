// Refresh wiki title art for auras outside the simulator's roll registry.
// Requires cheerio: npm install --prefix test-results/wiki-tools cheerio
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const cheerio = require(path.join(process.env.WIKI_STYLE_DEPS || path.resolve(__dirname, '../test-results/wiki-tools/node_modules'), 'cheerio'));
const postcss = require(path.join(process.env.WIKI_STYLE_DEPS || path.resolve(__dirname, '../test-results/wiki-tools/node_modules'), 'postcss'));
const selectorParser = require(path.join(process.env.WIKI_STYLE_DEPS || path.resolve(__dirname, '../test-results/wiki-tools/node_modules'), 'postcss-selector-parser'));
const titleRepairs = require('../scripts/wiki-title-repairs.js');
const root = path.resolve(__dirname, '..');
const reference = JSON.parse(fs.readFileSync(path.join(root, 'data/auras/wiki-reference.json'), 'utf8'));
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'scripts/wiki-title-data.js'), 'utf8'), context);
const normalize = title => title.replace(/_/g, ' ').toLowerCase();
const canonical = title => {
    let key = normalize(title);
    const visited = new Set();
    while (reference.aliases[key] && !visited.has(key)) { visited.add(key); key = reference.aliases[key]; }
    return key;
};
const styled = new Set(Object.values(context.WikiTitleData.auras).map(art => canonical(decodeURIComponent(new URL(art.source).pathname.slice(6)))));
const missing = reference.pages.filter(page => !styled.has(normalize(page.title)));
const allowedTags = new Set(['span', 'b', 'i', 'big', 'small', 'br']);
const allowedAttributes = new Set(['style', 'class', 'data-text', 'data-textstroke', 'data-gradient', 'data-colors', 'data-width', 'data-color']);
const animationNames = new Set([...fs.readFileSync(path.join(root, 'styles/wiki-title-effects.css'), 'utf8').matchAll(/@(?:-webkit-)?keyframes\s+wiki-([\w-]+)/g)].map(match => match[1]));
function sanitize(markup) {
    const $ = cheerio.load(markup, {}, false);
    $('script,style,iframe,img,svg,object,embed').remove();
    $('*').each((_, element) => {
        if (!allowedTags.has(element.name)) { $(element).replaceWith($(element).contents()); return; }
        for (const name of Object.keys(element.attribs)) if (!allowedAttributes.has(name)) $(element).removeAttr(name);
        if (element.attribs.class) $(element).attr('class', element.attribs.class.split(/\s+/).map(name => 'wiki-ref-' + name).join(' '));
        if (element.attribs.style) {
            const style = element.attribs.style.split(';').map(part => {
                const colon = part.indexOf(':');
                if (colon < 0) return '';
                const property = part.slice(0, colon).trim().toLowerCase();
                let value = part.slice(colon + 1).trim();
                if (!property || !value || /url\s*\(|expression\s*\(|javascript:|@import/i.test(value) || /^(behavior|-moz-binding)$/.test(property)) return '';
                if (property === 'position' && /fixed|sticky/.test(value)) value = 'relative';
                if (/(^|-)animation/.test(property)) value = value.replace(/[\w-]+/g, token => animationNames.has(token) ? 'wiki-' + token : token);
                const closers = (value.match(/\(/g) || []).length - (value.match(/\)/g) || []).length;
                return property + ':' + value + ')'.repeat(Math.max(0, closers));
            }).filter(Boolean).join(';');
            $(element).attr('style', titleRepairs.repairStyle(style));
        }
    });
    return $.html();
}
(async () => {
    const titles = {};
    for (let index = 0; index < missing.length; index += 40) {
        const batch = missing.slice(index, index + 40);
        const text = batch.map((page, position) => `<div data-aura-index="${position}">{{Aura|${page.title}}}</div>`).join('\n');
        const params = new URLSearchParams({ action: 'parse', text, contentmodel: 'wikitext', prop: 'text', format: 'json' });
        const response = await fetch('https://sol-rng.fandom.com/api.php?' + params);
        if (!response.ok) throw new Error('Wiki parse API returned ' + response.status);
        const data = await response.json();
        if (data.error) throw new Error(data.error.info);
        const $ = cheerio.load(data.parse.text['*']);
        batch.forEach((page, position) => {
            const art = $(`[data-aura-index="${position}"]`);
            if (!art.length || !art.text().trim()) throw new Error('Missing title artwork: ' + page.title);
            titles[page.title] = { source: page.source, markup: sanitize(art.html()) };
        });
    }
    fs.writeFileSync(path.join(root, 'scripts/directory-title-data.js'), '// Attributed wiki title artwork for directory-only auras.\n// Generated by tools/fetch-directory-title-art.cjs; see data/auras/README.md.\nObject.assign(globalThis.WikiTitleData.auras, ' + JSON.stringify(titles, null, 2) + ');\n');
    console.log('Saved wiki title artwork for ' + missing.length + ' additional auras.');
    const classes = [...new Set(Object.values(titles).flatMap(art => [...art.markup.matchAll(/class="([^"]*)"/g)].flatMap(match => match[1].split(/\s+/))))];
    const css = fs.readFileSync(path.join(root, 'styles/wiki-title-effects.css'), 'utf8');
    const missingClasses = new Set(classes.filter(name => !css.includes('.' + name)).map(name => name.slice('wiki-ref-'.length)));
    const params = new URLSearchParams({ action: 'query', prop: 'revisions', rvprop: 'content', rvslots: 'main', titles: 'MediaWiki:AuraKeyframes.css', format: 'json', formatversion: '2' });
    const cssData = await (await fetch('https://sol-rng.fandom.com/api.php?' + params)).json();
    const sourceCss = postcss.parse(cssData.query.pages[0].revisions[0].slots.main.content);
    const allAnimations = new Set();
    sourceCss.walkAtRules(/keyframes$/i, rule => allAnimations.add(rule.params));
    const neededAnimations = new Set();
    const renameAnimations = value => value.replace(/[\w-]+/g, token => {
        if (!allAnimations.has(token)) return token;
        neededAnimations.add(token);
        return 'wiki-' + token;
    });
    const extracted = postcss.root();
    sourceCss.walkRules(rule => {
        if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
        let selected = false;
        const selector = selectorParser(selectors => selectors.each(selector => selector.walkClasses(node => {
            if (missingClasses.has(node.value)) selected = true;
            node.value = 'wiki-ref-' + node.value;
        }))).processSync(rule.selector);
        if (!selected) return;
        const copy = rule.clone({ selector: '.wiki-title ' + selector });
        copy.walkDecls(/animation/, declaration => { declaration.value = renameAnimations(declaration.value); });
        extracted.append(copy);
    });
    sourceCss.walkAtRules(/keyframes$/i, rule => {
        if (neededAnimations.has(rule.params)) extracted.append(rule.clone({ params: 'wiki-' + rule.params }));
    });
    const existingFonts = (fs.readFileSync(path.join(root, 'styles/wiki-title-fonts.css'), 'utf8') + fs.readFileSync(path.join(root, 'index.html'), 'utf8')).replace(/%20|\+/g, ' ');
    const normalizedFonts = existingFonts.toLowerCase().replace(/[^a-z]/g, '');
    const fonts = [...new Set(Object.values(titles).flatMap(art => [...art.markup.matchAll(/font-family:([^;"<]+)/g)].map(match => match[1].split(',')[0].replace(/['"]/g, '').trim())))].filter(font => !normalizedFonts.includes(font.toLowerCase().replace(/[^a-z]/g, '')) && !/^(Arial|Helvetica|Times New Roman|sans-serif|serif|monospace|cursive|fantasy)$/i.test(font));
    const imports = fonts.map(font => `@import url('https://fonts.googleapis.com/css2?family=${encodeURIComponent(font).replace(/%20/g, '+')}&display=swap');`).join('\n');
    const attribution='/* Sol’s RNG Wiki contributors, CC BY-SA 3.0; see data/auras/README.md. */\n';
    fs.writeFileSync(path.join(root, 'styles/directory-title-fonts.css'), attribution + imports + '\n');
    fs.writeFileSync(path.join(root, 'styles/directory-title-effects.css'), attribution + extracted.toString() + '\n');
    console.log('Saved additional title effects and fonts:', fonts);
})().catch(error => { console.error(error); process.exitCode = 1; });
