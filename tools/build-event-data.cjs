// Compile reviewed event JSON into a synchronous bundle (also works on file://).
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const event = JSON.parse(fs.readFileSync(path.join(root, 'data/events/halloween2026.json'), 'utf8'));
if (event.id !== 'halloween26' || !['upcoming', 'ready'].includes(event.status) || typeof event.defaultEnabled !== 'boolean'
    || !Array.isArray(event.auras)) throw new Error('Invalid Halloween 2026 event metadata');
const names = new Set();
for (const aura of event.auras) {
    if (typeof aura.name !== 'string' || !aura.name.trim() || names.has(aura.name)
        || !Number.isFinite(aura.chance) || aura.chance < 1) throw new Error('Invalid or duplicate event aura');
    names.add(aura.name);
}
fs.writeFileSync(path.join(root, 'scripts/event-data.js'), '// Generated by tools/build-event-data.cjs from data/events/halloween2026.json.\n'
    + 'globalThis.EventData = ' + JSON.stringify({ halloween26: event }, null, 2) + ';\n');
